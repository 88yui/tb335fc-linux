/* 采集循环实测的帧间隔（ms），用于自适应 TNR 与帧预算判断 */
static volatile double g_framedt_ms=33.0;

/* ---- async encoder worker (ISP + ffmpeg pipe) ---- */
typedef struct { int slot; } VJob;
static VJob g_jq[8];
static int g_jhead=0,g_jtail=0,g_jcount=0,g_jskip=0,g_jquit=0;
static pthread_mutex_t g_jmtx=PTHREAD_MUTEX_INITIALIZER;
static pthread_cond_t g_jcv=PTHREAD_COND_INITIALIZER;
static pthread_t g_jth;
static double g_tisp=0,g_twr=0; static long g_tn=0; static int g_vtiming=0;
static void *venc_thread(void *arg){
  (void)arg;
  for(;;){
    pthread_mutex_lock(&g_jmtx);
    while(g_jcount==0 && !g_jquit) pthread_cond_wait(&g_jcv,&g_jmtx);
    if(g_jcount==0 && g_jquit){ pthread_mutex_unlock(&g_jmtx); break; }
    VJob j=g_jq[g_jhead]; g_jhead=(g_jhead+1)%8; g_jcount--;
    pthread_mutex_unlock(&g_jmtx);
    { /* 自适应 TNR：帧间隔 >=45ms（<=22fps）才开，30fps 时单帧预算 33ms 放不下 TNR(+12ms) */
      static struct timespec lastj; static int have_lastj=0, tnr_state=-1;
      struct timespec nowj; clock_gettime(CLOCK_MONOTONIC,&nowj);
      if(have_lastj){
        double dj=g_framedt_ms;
        int want=(dj>=45.0);
        if(want!=tnr_state && g_tn>0) printf("VENC adaptive TNR=%d (frame gap %.1fms)\n",want,dj);
        if(want!=tnr_state){ isp_half_set_tnr(want); tnr_state=want; }
      }
      lastj=nowj; have_lastj=1;
    }
    struct timespec a,b,c; clock_gettime(CLOCK_MONOTONIC,&a);
    uint8_t *rgb=NULL; int tdone=0;
    if(g_feedfd>=0 && g_ffmt.fourcc==CAMFEED_FOURCC_YUYV){
      /* 融合快路：解码/统计一次后直接在应用要求的尺寸做 tone + YUYV，省掉全分辨率 RGB 缓冲与二次缩放 */
      static unsigned char *fyb=NULL; static size_t fybsz=0;
      size_t need=(size_t)g_ffmt.width*(size_t)g_ffmt.height*2;
      if(fybsz<need){ unsigned char*np=(unsigned char*)realloc(fyb,need); if(np){ fyb=np; fybsz=need; } }
      if(fybsz>=need && isp_half_process_yuyv(&g_isp,slot_ptr[j.slot],61,"patch",1,1,g_vcsup,g_vcontrast,g_vgamma,
             (int)g_ffmt.width,(int)g_ffmt.height,(int)(g_ffmt.width*2),fyb)==0){
        clock_gettime(CLOCK_MONOTONIC,&b);
        ssize_t wrn=write(g_feedfd,fyb,need);
        if(wrn==(ssize_t)need){ g_venc++; g_feed_ok++; } else g_feed_skip++;
        tdone=1;
      } else g_feed_skip++;
    } else if(isp_half_process(&g_isp,slot_ptr[j.slot],61,"patch",1,1,g_vcsup,g_vcontrast,g_vgamma,0,&rgb)==0){
      clock_gettime(CLOCK_MONOTONIC,&b);
      size_t nb=(size_t)g_isp.w*g_isp.h*3;
      if(g_vpipe){ if(fwrite(rgb,1,nb,g_vpipe)==nb) g_venc++; }
      else if(g_feedfd>=0){
        unsigned char *fb=NULL; size_t fn=0;
        if(feed_make(rgb,g_isp.w,g_isp.h,&g_ffmt,&fb,&fn)==0){
          ssize_t wrn=write(g_feedfd,fb,fn);
          if(wrn==(ssize_t)fn){ g_venc++; g_feed_ok++; } else g_feed_skip++;
        } else g_feed_skip++;
      }
      else g_venc++;
      tdone=1;
    }
    clock_gettime(CLOCK_MONOTONIC,&c);
    if(tdone){
      double dt_isp=(b.tv_sec-a.tv_sec)*1e3+(b.tv_nsec-a.tv_nsec)/1e6;
      double dt_wr=(c.tv_sec-b.tv_sec)*1e3+(c.tv_nsec-b.tv_nsec)/1e6;
      g_tisp+=dt_isp; g_twr+=dt_wr; g_tn++;
      if(g_tn%30==0) printf("VENC perf n=%d isp=%.1fms wr=%.1fms\n",g_tn,g_tisp/g_tn,g_twr/g_tn);
    }
  }
  return NULL;
}
static void venc_submit(int slot){
  pthread_mutex_lock(&g_jmtx);
  if(g_jcount<8){ g_jq[g_jtail].slot=slot; g_jtail=(g_jtail+1)%8; g_jcount++; pthread_cond_signal(&g_jcv); }
  else g_jskip++;
  pthread_mutex_unlock(&g_jmtx);
}
