/* 采样统计（前置 40bit LE RAW10，stride 3248） */
static void framestats(uint8_t *p, size_t bytes, double *mean, double *clip, double *pmax, double *p995){
  const size_t rowb=3248; size_t rows=bytes/rowb; const int ng=648;
  double sum=0; long n=0,nc=0; unsigned mx=0;
  static unsigned hist[1024];
  for(int i=0;i<1024;i++) hist[i]=0;
  for(size_t y=0;y<rows;y+=4){
    const uint8_t *row=p+y*rowb;
    for(int g=0;g<ng;g+=7){
      const uint8_t *b=row+g*5;
      uint64_t wq=(uint64_t)b[0]|((uint64_t)b[1]<<8)|((uint64_t)b[2]<<16)|((uint64_t)b[3]<<24)|((uint64_t)b[4]<<32);
      unsigned px[4]={ (unsigned)(wq&0x3FF),(unsigned)((wq>>10)&0x3FF),(unsigned)((wq>>20)&0x3FF),(unsigned)((wq>>30)&0x3FF) };
      for(int k=0;k<4;k++){ unsigned v=px[k]; if(v>mx)mx=v; sum+=v; n++; if(v>=1000)nc++; hist[v&0x3FFu]++; }
    }
  }
  *mean=sum/(double)(n?n:1); *clip=(double)nc/(double)(n?n:1); *pmax=(double)mx;
  { long want=(long)(0.995*(double)n); long acc=0; int v=1023;
    for(v=0;v<1024;v++){ acc+=hist[v]; if(acc>=want) break; }
    if(v>1023)v=1023; *p995=(double)v; }
}

/* 前置 GC05A2：曝光 0x0202/0203（16bit）、增益 0x0204（主）/0x0205=0、VTS 0x0340/0341 */
static void sen_set_exp(int exp){
  if(exp>0x3FF0) exp=0x3FF0;
  if(exp<1) exp=1;
  swrite(0x0202,(uint8_t)((exp>>8)&0xFF));
  swrite(0x0203,(uint8_t)(exp&0xFF));
  g_cur_exp=exp;
}
static void sen_set_exp_rev(int exp){ sen_set_exp(exp); }
static int sen_rd_exp(void){ int h=sread(0x0202)&0xFF, l=sread(0x0203)&0xFF; return (h<<8)|l; }
static void sen_set_gain(int code){
  if(code<0) code=0; if(code>0xFF) code=0xFF;
  swrite(0x0204,(uint8_t)(code&0xFF));
  swrite(0x0205,0);
  g_cur_gain=code;
}
static void sen_set_vts(int vts){
  if(vts<64) vts=64; if(vts>0x3FFF) vts=0x3FFF;
  swrite(0x0340,(uint8_t)((vts>>8)&0xFF));
  swrite(0x0341,(uint8_t)(vts&0xFF));
  g_vts_cur=vts;
}
/* code -> 亮度倍率 查找表（由 -G 标定扫描实测填充），表间线性插值 */
static const int   GMAP_C[] = {0,4,8,16,32,64,128,192,255};
static const double GMAP_M[]= {0.45,1.00,1.18,1.35,1.45,1.50,1.60,1.78,1.96};
static const int GMAP_N = (int)(sizeof(GMAP_C)/sizeof(GMAP_C[0]));
static double gain_mult(int code){
  if(code<=GMAP_C[0]) return GMAP_M[0];
  for(int i=1;i<GMAP_N;i++){
    if(code<=GMAP_C[i]){
      double t=(double)(code-GMAP_C[i-1])/(double)(GMAP_C[i]-GMAP_C[i-1]);
      return GMAP_M[i-1]+t*(GMAP_M[i]-GMAP_M[i-1]);
    }
  }
  return GMAP_M[GMAP_N-1];
}
static int gain_code_for(double mult, int maxcode){
  if(mult<=GMAP_M[0]) return 0;
  for(int i=1;i<GMAP_N;i++){
    if(mult<=GMAP_M[i]){
      double t=(mult-GMAP_M[i-1])/(GMAP_M[i]-GMAP_M[i-1]);
      int c=(int)(GMAP_C[i-1]+t*(GMAP_C[i]-GMAP_C[i-1])+0.5);
      return c>maxcode?maxcode:c;
    }
  }
  return maxcode;
}
