static void ae_update(uint8_t *p, size_t bytes){
  static int aecnt=0, nextat=0;
  if(aecnt++ < nextat) return;   /* 传感器生效有 ~2 帧延迟：至少隔 2 帧再决策，避免振荡 */
  double mean,clip,pmax,p995; framestats(p,bytes,&mean,&clip,&pmax,&p995);
  double blk=61.0;
  double s=p995-blk; if(s<1.0) s=1.0;
  double target=(double)g_ae_target_p995;
  double f=target/s; if(f<0.25)f=0.25; if(f>4.0)f=4.0;
  if(clip>0.002) f=0.75; else if(clip>0.0005 && f>1.0) f=1.0;
  /* 死区 + 阻尼 + 单步限幅 */
  if(fabs(f-1.0)<0.08){
    if(g_aestep_at==0)
      printf("AE hold mean=%.1f p995=%.0f s=%.1f clip=%.4f exp=%d vts=%d gain=%d\n",mean,p995,s,clip,g_cur_exp,g_vts_cur,g_cur_gain);
    return;
  }
  { double df=f-1.0; double lim=(fabs(df)>0.8)?0.90:((fabs(df)>0.3)?0.35:0.15);
    double f2=1.0+df*0.5; if(f2>1.0+lim)f2=1.0+lim; if(f2<1.0-lim)f2=1.0-lim; f=f2; }
  { int wait=(fabs(f-1.0)>0.30)?2:3; if(g_aeskip>0) wait=g_aeskip; nextat=aecnt+wait-1; }
  int nexp=g_cur_exp, nvts=g_vts_cur, ngain=g_cur_gain;
  double curm=gain_mult(g_cur_gain); if(curm<0.05)curm=0.05;
  if(f>=1.0){
    /* 变亮：先曝光 -> 再 VTS（降帧率换曝光）-> 曝光顶格才加增益 */
    double want=(double)g_cur_exp*f;
    int maxexp=g_vts_cur-16;
    if(want<=maxexp){ nexp=(int)(want+0.5); if(nexp>maxexp)nexp=maxexp; }
    else {
      int nv=(int)(want+16.0); if(nv<g_vts_cur)nv=g_vts_cur; if(nv>g_ae_vts_max)nv=g_ae_vts_max;
      nvts=nv; nexp=nvts-16; if(nexp>g_ae_exp_cap)nexp=g_ae_exp_cap;
      double cov=(double)nexp/(double)(g_cur_exp?g_cur_exp:1);
      double res=f/cov;
      if(res>1.03){ ngain=gain_code_for(curm*res,g_aemaxgain); }
    }
  } else {
    /* 变暗：先降增益（保 SNR）-> 再降曝光 -> 富余很多时降 VTS 提高帧率 */
    if(g_cur_gain>0){
      double newm=curm*f; double m0=gain_mult(0); if(newm<m0)newm=m0;
      ngain=gain_code_for(newm,g_aemaxgain);
    }
    double cov=gain_mult(ngain)/curm; if(cov>0.99)cov=0.99;
    double res=f/cov;
    if(res<1.0){ int ne=(int)((double)g_cur_exp*res+0.5); if(ne<16)ne=16; nexp=ne; }
    if(g_vts_cur>g_ae_vts_min && f<0.5){
      int nv=(int)((double)nexp*1.5+32); if(nv<g_ae_vts_min)nv=g_ae_vts_min; if(nv<g_vts_cur)nvts=nv;
    }
  }
  if(nvts<g_ae_vts_min) nvts=g_ae_vts_min; if(nvts>g_ae_vts_max) nvts=g_ae_vts_max;
  if(nexp<16)nexp=16; if(nexp>nvts-16)nexp=nvts-16; if(nexp>g_ae_exp_cap)nexp=g_ae_exp_cap;
  printf("AE mean=%.1f p995=%.0f s=%.1f clip=%.4f pmax=%.0f f=%.2f exp %d->%d vts %d->%d gain %d->%d (period %.0fms)\n",
    mean,p995,s,clip,pmax,f,g_cur_exp,nexp,g_vts_cur,nvts,g_cur_gain,ngain,(double)nvts*0.01332);
  { int changed=(nexp!=g_cur_exp)||(nvts!=g_vts_cur)||(ngain!=g_cur_gain);
    static int limcnt=0;
    if(!changed){ if((limcnt++%10)==0) printf("AE limit mean=%.1f p995=%.0f s=%.1f (target %d 不可达) exp=%d vts=%d gain=%d\n",
        mean,p995,s,g_ae_target_p995,g_cur_exp,g_vts_cur,g_cur_gain); return; }
    if(g_ae_gh){ sen_gh_begin();
      if(nvts!=g_vts_cur) sen_set_vts(nvts);
      if(nexp!=g_cur_exp) sen_set_exp(nexp);
      if(ngain!=g_cur_gain) sen_set_gain(ngain);
      sen_gh_launch();
    } else {
      if(nvts>g_vts_cur){ sen_set_vts(nvts); if(nexp!=g_cur_exp) sen_set_exp(nexp); }
      else { if(nexp!=g_cur_exp) sen_set_exp(nexp); if(nvts!=g_vts_cur) sen_set_vts(nvts); }
      if(ngain!=g_cur_gain) sen_set_gain(ngain);
    } }
  { int rvts=(((int)(sread(0x320E)&0xFF))<<8)|(int)(sread(0x320F)&0xFF);
    int rexp=sen_rd_exp();
    printf("AE[reg] VTS=%d EXP=%d GAIN3E07=0x%02X 3E08=0x%02X\n",rvts,rexp,(int)(sread(0x3E07)&0xFF),(int)(sread(0x3E08)&0xFF)); }
}
