/* 采样统计：每 4 行取 1 行、每 7 组取 1 组（约 286k 像素） */
static void framestats(uint8_t *p, size_t bytes, double *mean, double *clip, double *pmax, double *p995){
  const size_t rowb=4080; size_t rows=bytes/rowb;
  double sum=0; long n=0,nc=0; unsigned mx=0;
  static unsigned hist[1024];
  for(int i=0;i<1024;i++) hist[i]=0;
  for(size_t y=0;y<rows;y+=4){
    const uint8_t *row=p+y*rowb;
    for(size_t g=0;g<816;g+=7){
      const uint8_t *b=row+g*5;
      unsigned long long w=(unsigned long long)b[0]|((unsigned long long)b[1]<<8)
        |((unsigned long long)b[2]<<16)|((unsigned long long)b[3]<<24)|((unsigned long long)b[4]<<32);
      unsigned px[4]={(unsigned)(w&0x3FF),(unsigned)((w>>10)&0x3FF),(unsigned)((w>>20)&0x3FF),(unsigned)((w>>30)&0x3FF)};
      for(int k=0;k<4;k++){ unsigned v=px[k]; if(v>mx)mx=v; sum+=v; n++; if(v>=1000)nc++; hist[v&0x3FF]++; }
    }
  }
  *mean=sum/(double)(n?n:1); *clip=(double)nc/(double)(n?n:1); *pmax=(double)mx;
  { long want=(long)(0.995*(double)n); long acc=0; int v=1023;
    for(v=0;v<1024;v++){ acc+=hist[v]; if(acc>=want) break; }
    if(v>1023)v=1023; *p995=(double)v; }
}
/* 曝光编码：取自厂商 imgsensor_isp6s.ko 的 SC820ACS set_shutter@0x12588 反汇编
   0x3E00=(exp>>11)&0x1F, 0x3E01=(exp>>3)&0xFF, 0x3E02=(exp&7)<<5 ; clamp 0x3FFA */
static void sen_set_exp(int exp){
  if(exp>0x3FFA) exp=0x3FFA;
  if(exp<1) exp=1;
  swrite(0x3E00,(uint8_t)((exp>>11)&0x1F));
  swrite(0x3E01,(uint8_t)((exp>>3)&0xFF));
  swrite(0x3E02,(uint8_t)((exp&0x07)<<5));
  g_cur_exp=exp;
}
/* 反序写（0x3E00 最后），用于测试传感器是否以 0x3E00 为 latch 触发 */
static void sen_set_exp_rev(int exp){
  if(exp>0x3FFA) exp=0x3FFA;
  swrite(0x3E02,(uint8_t)((exp&0x07)<<5));
  swrite(0x3E01,(uint8_t)((exp>>3)&0xFF));
  swrite(0x3E00,(uint8_t)((exp>>11)&0x1F));
  g_cur_exp=exp;
}
static int sen_rd_exp(void){
  int e0=sread(0x3E00)&0x1F, e1=sread(0x3E01)&0xFF, e2=(sread(0x3E02)&0xFF)>>5;
  return (e0<<11)|(e1<<3)|e2;
}
/* 增益：实测 0x3E07 = 线性增益码（0x80≈1x，0x00≈0，0xFF≈2x）；0x3E08 行为非单调（疑似模式位），AE 不使用 */
static void sen_set_gain(int code){
  if(code<0) code=0; if(code>0xFF) code=0xFF;
  swrite(0x3E07,(uint8_t)(code&0xFF));
  g_cur_gain=code;
}
